class CommunityPost {
  final String title;
  final String author;
  final String area;
  final String category;
  final String content;
  final String action;
  final String icon;

  const CommunityPost({
    required this.title,
    required this.author,
    required this.area,
    required this.category,
    required this.content,
    required this.action,
    required this.icon,
  });
}
